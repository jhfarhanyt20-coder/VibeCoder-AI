"use strict"
const assert = require("node:assert/strict")
const { openAIUsage, anthropicUsage, estimateCost } = require("../core/llm/usage")
const U = require("../renderer/usage")
const { convertMessages } = require("../electron/messages.cjs")
const { modelPricing } = require("../core/llm/provider-meta")
const tokens = openAIUsage({ prompt_tokens: 1000, completion_tokens: 200, prompt_tokens_details: { cached_tokens: 400 }, completion_tokens_details: { reasoning_tokens: 50 }, cost: 0.00321 })
assert.equal(U.sumTokens(tokens), 1200)
assert.equal(tokens.cost, 0.00321)
assert.equal(anthropicUsage({ input_tokens: 5, output_tokens: 10, cost: 0 }).cost, 0)
const estimated = estimateCost({ input: 600, output: 150, reasoning: 50, cache: { read: 400, write: 0 } }, { input: 2, output: 8, cache_read: 0.2 })
assert.ok(Math.abs(estimated.cost - 0.00288) < 1e-10)
assert.equal(estimated.costSource, "estimated")
assert.equal(estimateCost(tokens, { input: 999, output: 999 }).cost, 0.00321)
assert.equal(estimateCost({}, null).cost, undefined)
assert.equal(modelPricing({ baseURL: "https://custom.example/v1", model: "paid" }, __dirname), null)
const usage = U.emptyUsage()
U.addStep(usage, "step-1", tokens, 0.001, "provider")
U.addStep(usage, "step-1", tokens, 0.00321, "provider")
assert.equal(U.totals(usage).steps, 1)
assert.equal(U.totals(usage).cost, 0.00321)
const messages = convertMessages({ messages: [{ role: "assistant", parts: [{ type: "text", text: "Done" }], usage: estimated }], updatedAt: 0 })
const restored = U.totals(U.usageFromMessages(messages))
assert.equal(restored.cost, estimated.cost)
assert.equal(restored.estimated, true)
U.addStep(usage, "step-2", { input: 10 })
assert.equal(U.totals(usage).unknownCost, 1)
console.log("PASS usage cost: provider charge/zero preserved, cache and reasoning priced once, estimates distinguished, unknown pricing not free, repeated usage events deduplicated, history retains cost")
