assert.match(renderer, /data\.retryable !== false && !state\.userStopped && \(isRetryableRunError\(real\) \|\| unexpectedAbort\)/)
assert.match(backend, /vibe\.session\.compact\(idOf\(a\), \{ reason: a\.reason === "auto" \? "auto" : "manual", summaryModel: "session" \}\)/)
